static const uint8_t *glyph(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    const char *p = strchr(notice_chars + 1, c);
    return notice_font[p ? (int)(p - notice_chars) : 0];
}

void notice_draw_fb(uint32_t *fb, int w, int h, const char *const *lines, int n)
{
    int x, y, l, i, r, c, scale, x0, y0, len;
    uint32_t bg = 0xff4c0a0au, fg = 0xffffffffu;
    if (!fb || w <= 0 || h <= 0) return;
    for (y = 0; y < h; y++) {
        uint32_t *row = fb + (long)y * w;
        for (x = 0; x < w; x++) row[x] = bg;
    }
    if (n > 7) n = 7;
    scale = (w >= 200) ? 2 : 1;
    y0 = (h - n * (8 * scale + 4)) / 2;
    if (y0 < 8) y0 = 8;
    for (l = 0; l < n; l++) {
        len = (int)strlen(lines[l]);
        if (len > 21) len = 21;
        x0 = (w - len * 6 * scale) / 2;
        if (x0 < 4) x0 = 4;
        for (i = 0; i < len; i++) {
            const uint8_t *g = glyph(lines[l][i]);
            for (r = 0; r < 7; r++)
                for (c = 0; c < 5; c++) {
                    if (!((g[r] >> (4 - c)) & 1)) continue;
                    int px = x0 + i * 6 * scale + c * scale;
                    int py = y0 + l * (8 * scale + 4) + r * scale;
                    int sy, sx;
                    for (sy = 0; sy < scale; sy++)
                        for (sx = 0; sx < scale; sx++) {
                            int xx = px + sx, yy = py + sy;
                            if (xx >= 0 && yy >= 0 && xx < w && yy < h)
                                fb[(long)yy * w + xx] = fg;
                        }
                }
        }
    }
}
