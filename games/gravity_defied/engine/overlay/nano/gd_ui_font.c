static const GdUiFont font_large = {22, 22, 28, bits_large, gly_large};

const GdUiFont *gd_ui_font(int px)
{
    if (px >= 19) return &font_large;
    if (px >= 14) return &font_medium;
    return &font_small;
}

int gd_ui_font_height(int px) { return gd_ui_font(px)->height; }

int gd_ui_char_width(int px, int c)
{
    const GdUiFont *f = gd_ui_font(px);
    if (c < 32 || c > 126) c = 32;
    return f->g[c - 32].adv;
}

int gd_ui_text_width(int px, const char *s, int n)
{
    int w = 0, i;
    if (!s) return 0;
    if (n < 0) n = (int)strlen(s);
    for (i = 0; i < n && s[i]; i++) w += gd_ui_char_width(px, (unsigned char)s[i]);
    return w;
}

void gd_ui_draw_text(uint32_t *fb, int fb_w, int fb_h,
                     int x, int y, const char *s, int n, int px,
                     uint32_t color, int cx, int cy, int cw, int ch)
{
    const GdUiFont *f;
    int i, cx1, cy1, pen;
    if (!fb || !s || fb_w < 1 || fb_h < 1) return;
    if (n < 0) n = (int)strlen(s);
    f = gd_ui_font(px);
    color |= 0xff000000u;
    cx1 = cx + cw; cy1 = cy + ch;
    if (cx < 0) cx = 0;
    if (cy < 0) cy = 0;
    if (cx1 > fb_w) cx1 = fb_w;
    if (cy1 > fb_h) cy1 = fb_h;
    pen = x;
    for (i = 0; i < n && s[i]; i++) {
        int c = (unsigned char)s[i];
        const GdUiGlyph *g;
        int gx, gy, rowb, yy, xx;
        if (c < 32 || c > 126) c = 63;
        g = &f->g[c - 32];
        gx = pen + g->xoff;
        gy = y + g->yoff - f->ascent;
        rowb = (g->w + 7) >> 3;
        for (yy = 0; yy < g->h; yy++) {
            int py = gy + yy;
            const uint8_t *row;
            if (py < cy || py >= cy1) continue;
            row = f->bits + g->off + yy * rowb;
            for (xx = 0; xx < g->w; xx++) {
                int pxp;
                if (!(row[xx >> 3] & (uint8_t)(0x80u >> (xx & 7)))) continue;
                pxp = gx + xx;
                if (pxp < cx || pxp >= cx1) continue;
                fb[(long)py * fb_w + pxp] = color;
            }
        }
        pen += g->adv;
    }
}

