/* notice.c: an on-screen message for when the game cannot start (nano7kit, LGPL-3.0-or-later).
 * A full-panel dark red screen with up to 7 lines of up to 21 capitals, drawn from one
 * 128x64 RGBA4444 texture (16 KB, static: no allocation at all). Used instead of starting the engine when memory is
 * short, so the iPod never runs into the OS allocator's out-of-memory reboot. */
#include <stdint.h>
#include <string.h>
#include "gl.h"
#include "notice.h"
#include "gl_left.h"

