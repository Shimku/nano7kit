#define TW 128
#define TH 64
static GLuint tex;
static uint16_t texels[TW * TH];

static const uint8_t *glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    const char *p = strchr(notice_chars + 1, c);
    return notice_font[p ? (int)(p - notice_chars) : 0];
}
/* the texel image, also used by the host test */
void notice_render(uint16_t *px, const char *const *lines, int n) {
    memset(px, 0, TW * TH * 2);
    if (n > 7) n = 7;
    for (int l = 0; l < n; l++) {
        int len = (int)strlen(lines[l]);
        if (len > 21) len = 21;
        int x0 = (TW - len * 6) / 2, y0 = l * 9 + 1;
        for (int i = 0; i < len; i++) {
            const uint8_t *g = glyph(lines[l][i]);
            for (int r = 0; r < 7; r++)
                for (int c = 0; c < 5; c++)
                    if (g[r] >> (4 - c) & 1) px[(y0 + r) * TW + x0 + i * 6 + c] = 0xFFFF;
        }
    }
}
void notice_reset(void) { tex = 0; }
void notice_draw(int w, int h, const char *const *lines, int n) {
    if (!tex) {
        notice_render(texels, lines, n);
        glGenTextures(1, &tex);
        if (tex) gll_note(tex);         /* gl_left.c: the next port deletes it after we quit */
        if (tex) {
            glBindTexture(GL_TEXTURE_2D, tex);
            glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
            glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
            glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, TW, TH, 0, GL_RGBA, GL_UNSIGNED_SHORT_4_4_4_4, texels);
        }
    }
    glViewport(0, 0, w, h);
    glMatrixMode(GL_PROJECTION); glLoadIdentity();
    glMatrixMode(GL_MODELVIEW); glLoadIdentity();
    glDisable(GL_DEPTH_TEST); glDisable(GL_CULL_FACE); glDisable(GL_LIGHTING);
    glClearColor(0.30f, 0.04f, 0.04f, 1.f);
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);
    if (!tex) return;                   /* no texture name: the red screen alone says it */
    /* 128x64 texels at 1.75x: 224x112 px, centred */
    float hx = 224.f / (float)w, hy = 112.f / (float)h;
    static const float uv[8] = {0, 1, 1, 1, 0, 0, 1, 0};
    float xy[8] = {-hx, -hy, hx, -hy, -hx, hy, hx, hy};
    glEnable(GL_TEXTURE_2D); glBindTexture(GL_TEXTURE_2D, tex);
    glEnable(GL_BLEND); glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);
    glDisableClientState(GL_COLOR_ARRAY); glDisableClientState(GL_NORMAL_ARRAY);
    glColor4f(1.f, 1.f, 1.f, 1.f);
    glEnableClientState(GL_VERTEX_ARRAY); glEnableClientState(GL_TEXTURE_COORD_ARRAY);
    glVertexPointer(2, GL_FLOAT, 0, xy);
    glTexCoordPointer(2, GL_FLOAT, 0, uv);
    glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
}
