int ab_stub_audio(const char *name, void **out, uint32_t *len) {
    int k = audio_kind(name);
    uint8_t *b;
    if (!out || !len) return -1;
    *out = 0; *len = 0;
    if (k == 1) {
        *out = make_wav(len);
        return *out ? 1 : -1;
    }
    if (k != 2) return 0;
    b = (uint8_t *)malloc(sizeof k_mp3);
    if (!b) return -1;
    memcpy(b, k_mp3, sizeof k_mp3);
    *out = b;
    *len = (uint32_t)sizeof k_mp3;
    return 1;
}
