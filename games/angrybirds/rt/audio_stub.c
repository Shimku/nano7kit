/* audio_stub.c: tiny silent WAV / MPEG frames for skipped SFX and Music.
 * convert_assets.py does not copy wav/mp3 (RAM). playAudio still opens them. */
#include "audio_stub.h"
#include <stdlib.h>
#include <string.h>

static int audio_kind(const char *name) {
    size_t n, i;
    char ext[8];
    if (!name) return 0;
    n = strlen(name);
    if (n < 4) return 0;
    for (i = 0; i < 5 && i <= n; i++) {
        char c = name[n - 4 + i];
        if (c >= 'A' && c <= 'Z') c = (char)(c - 'A' + 'a');
        ext[i] = c;
    }
    ext[4] = 0;
    if (!strcmp(ext, ".wav")) return 1;
    if (!strcmp(ext, ".mp3")) return 2;
    return 0;
}

static void *make_wav(uint32_t *len) {
    enum { NS = 256 };
    uint32_t data = (uint32_t)NS * 2u, total = 44u + data, v;
    uint8_t *b = (uint8_t *)calloc(1, total);
    if (!b) return 0;
    memcpy(b, "RIFF", 4);
    v = total - 8; memcpy(b + 4, &v, 4);
    memcpy(b + 8, "WAVEfmt ", 8);
    v = 16; memcpy(b + 16, &v, 4);
    b[20] = 1; b[22] = 1;
    v = 22050; memcpy(b + 24, &v, 4);
    v = 44100; memcpy(b + 28, &v, 4);
    b[32] = 2; b[34] = 16;
    memcpy(b + 36, "data", 4);
    memcpy(b + 40, &data, 4);
    *len = total;
    return b;
}

